/// <summary>One method result inside an Authentication-Results header ("spf=pass ...").</summary>
public sealed class AuthMethod
{
    public string Method { get; init; } = "";          // spf, dkim, dmarc, compauth, arc, iprev, auth
    public string Result { get; init; } = "";          // pass, fail, softfail, neutral, none, temperror, permerror, ...
    public string Comment { get; init; } = "";
    public Dictionary<string, string> Props { get; } = new(StringComparer.OrdinalIgnoreCase);

    public string? Prop(string key) => Props.TryGetValue(key, out var v) ? v : null;

    public bool Passed => Result.Equals("pass", StringComparison.OrdinalIgnoreCase)
                          || Result.Equals("bestguesspass", StringComparison.OrdinalIgnoreCase);

    public override string ToString()
    {
        var props = string.Join(" ", Props.Select(p => $"{p.Key}={p.Value}"));
        return $"{Method}={Result}" + (props.Length > 0 ? " " + props : "") + (Comment.Length > 0 ? $" ({Comment})" : "");
    }
}

public sealed class AuthResultsHeader
{
    public string Source { get; init; } = "";          // header name, plus "i=1" for ARC
    public string? AuthServId { get; init; }
    public string Raw { get; init; } = "";
    public int Index { get; init; }
    public List<AuthMethod> Methods { get; } = new();

    public AuthMethod? Get(string method) => Methods.FirstOrDefault(m => m.Method.Equals(method, StringComparison.OrdinalIgnoreCase));
    public IEnumerable<AuthMethod> All(string method) => Methods.Where(m => m.Method.Equals(method, StringComparison.OrdinalIgnoreCase));
}

public sealed class ReceivedHop
{
    public int Index { get; init; }                    // 0 = topmost = last hop
    public string Raw { get; init; } = "";
    public string? FromHelo { get; init; }
    public string? FromHost { get; init; }             // the reverse DNS name the receiver saw
    public IPAddress? FromIp { get; init; }
    public string? ByHost { get; init; }
    public string? With { get; init; }
    public string? Tls { get; init; }
    public DateTimeOffset? Time { get; init; }
    public TimeSpan? DelayBefore { get; set; }         // time since the previous (older) hop
}

public sealed class DkimSignature
{
    public string Domain { get; init; } = "";          // d=
    public string Selector { get; init; } = "";        // s=
    public string Algorithm { get; init; } = "";       // a=
    public string Identity { get; init; } = "";        // i=
    public string SignedHeaders { get; init; } = "";   // h=
    public DateTimeOffset? Expires { get; init; }      // x=
    public DateTimeOffset? Signed { get; init; }       // t=
    public string Raw { get; init; } = "";
}

/// <summary>Everything a header block says, plus what can be derived from it.</summary>
public sealed class MailEvidence
{
    public HeaderBlock Headers { get; init; } = new();

    public string? From { get; set; }
    public string? FromDomain { get; set; }
    public string? FromDisplay { get; set; }
    public string? ReturnPath { get; set; }
    public string? EnvelopeDomain { get; set; }
    public string? Sender { get; set; }
    public string? ReplyTo { get; set; }
    public List<string> To { get; } = new();
    public string? Subject { get; set; }
    public DateTimeOffset? Date { get; set; }
    public string? MessageId { get; set; }

    public List<ReceivedHop> Hops { get; } = new();
    public List<AuthResultsHeader> AuthResults { get; } = new();
    public List<DkimSignature> DkimSignatures { get; } = new();
    public int ArcInstances { get; set; }
    public string? ReceivedSpf { get; set; }

    public IPAddress? SendingIp { get; set; }
    public string SendingIpSource { get; set; } = "";
    public string? SendingHost { get; set; }
    public string? SendingHelo { get; set; }

    public int? Scl { get; set; }
    public int? Bcl { get; set; }
    public string? SpamVerdict { get; set; }          // "SFV:SPM", "X-Spam-Status: Yes, score=..."
    public double? SpamScore { get; set; }
    public double? SpamThreshold { get; set; }
    public string? AuthAs { get; set; }               // X-MS-Exchange-Organization-AuthAs
    public bool IsListMail { get; set; }
    public bool IsAutoGenerated { get; set; }
    public string? Mailer { get; set; }

    // The verdict of the receiving side, from the topmost trustworthy Authentication-Results.
    public AuthResultsHeader? PrimaryAuth { get; set; }
    public string? SpfResult { get; set; }
    public string? SpfDomain { get; set; }             // smtp.mailfrom domain
    public List<(string Result, string Domain, string? Selector)> DkimResults { get; } = new();
    public string? DmarcResult { get; set; }
    public string? DmarcAction { get; set; }           // Microsoft action=none/quarantine/reject/oreject
    public string? DmarcPolicyThen { get; set; }       // p= as reported by Google/others
    public string? CompAuth { get; set; }
    public string? CompAuthReason { get; set; }

    public bool SpfAligned => DomainUtil.AlignedRelaxed(SpfDomain ?? EnvelopeDomain, FromDomain);
    public bool SpfPassed => SpfResult?.Equals("pass", StringComparison.OrdinalIgnoreCase) == true;

    public bool DkimAlignedPass => DkimResults.Any(d => d.Result.Equals("pass", StringComparison.OrdinalIgnoreCase)
                                                         && DomainUtil.AlignedRelaxed(d.Domain, FromDomain));
    public bool AnyDkimPass => DkimResults.Any(d => d.Result.Equals("pass", StringComparison.OrdinalIgnoreCase));

    /// <summary>
    /// Which aligned DMARC leg (SPF, DKIM, both or neither) carried the mail, i.e. which half
    /// of the setup must keep working.
    /// </summary>
    public string DmarcCarriedBy
    {
        get
        {
            bool spf = SpfPassed && SpfAligned;
            bool dkim = DkimAlignedPass;
            // The receiver did not evaluate DKIM (or did not stamp it), but the mail carried an
            // aligned signature: unknown, not failed. Some gateways stamp only spf=.
            if (!dkim && DkimNotReported && HasAlignedSignature)
                return spf ? "SPF (DKIM signed, not reported)" : "DKIM signed, not reported";
            return (spf, dkim) switch
            {
                (true, true) => "SPF and DKIM",
                (true, false) => "SPF only",
                (false, true) => "DKIM only",
                _ => "neither",
            };
        }
    }

    /// <summary>The trusted Authentication-Results has no dkim= entry at all.</summary>
    public bool DkimNotReported => PrimaryAuth is not null && !PrimaryAuth.Methods.Any(m => m.Method == "dkim");

    public bool HasAlignedSignature => DkimSignatures.Any(s => DomainUtil.AlignedRelaxed(s.Domain, FromDomain));

    public TimeSpan? TotalTransit
    {
        get
        {
            var times = Hops.Where(h => h.Time.HasValue).Select(h => h.Time!.Value).ToList();
            if (times.Count < 2) return null;
            return times.Max() - times.Min();
        }
    }

    public bool HasAnything => !Headers.IsEmpty;
}

public static class HeaderAnalyzer
{
    public static MailEvidence Analyze(string? text)
    {
        var headers = HeaderBlock.Parse(text);
        var e = new MailEvidence { Headers = headers };
        if (headers.IsEmpty) return e;

        // ---------------------------------------------------------------- identities
        var from = headers.First("From");
        e.From = HeaderBlock.ExtractAddress(from);
        e.FromDomain = e.From is null ? null : DomainUtil.DomainOf(e.From);
        if (from is not null)
        {
            var decoded = HeaderBlock.DecodeWords(from);
            int lt = decoded.IndexOf('<');
            e.FromDisplay = lt > 0 ? decoded[..lt].Trim().Trim('"') : null;
        }

        e.ReturnPath = HeaderBlock.ExtractAddress(headers.First("Return-Path"));
        e.EnvelopeDomain = e.ReturnPath is null ? null : DomainUtil.DomainOf(e.ReturnPath);
        e.Sender = HeaderBlock.ExtractAddress(headers.First("Sender"));
        e.ReplyTo = HeaderBlock.ExtractAddress(headers.First("Reply-To"));
        foreach (var to in headers.All("To").Concat(headers.All("Cc")))
            e.To.AddRange(HeaderBlock.ExtractAddresses(to.Value).Where(a => !e.To.Contains(a, StringComparer.OrdinalIgnoreCase)));
        e.Subject = HeaderBlock.DecodeWords(headers.First("Subject"));
        e.Date = ParseDate(headers.First("Date"));
        e.MessageId = headers.First("Message-ID")?.Trim();

        e.IsListMail = headers.Has("List-Id") || headers.Has("List-Unsubscribe") || headers.Has("Precedence") && (headers.First("Precedence") ?? "").Contains("bulk", StringComparison.OrdinalIgnoreCase);
        e.IsAutoGenerated = headers.Has("Auto-Submitted") && !(headers.First("Auto-Submitted") ?? "").Trim().Equals("no", StringComparison.OrdinalIgnoreCase);
        e.Mailer = headers.First("X-Mailer") ?? headers.First("User-Agent");
        e.AuthAs = headers.First("X-MS-Exchange-Organization-AuthAs")?.Trim();

        // ---------------------------------------------------------------- Received chain
        foreach (var f in headers.All("Received"))
        {
            var hop = ParseReceived(f.Value, e.Hops.Count);
            e.Hops.Add(hop);
        }
        for (int i = 0; i < e.Hops.Count - 1; i++)
        {
            var newer = e.Hops[i].Time;
            var older = e.Hops[i + 1].Time;
            if (newer.HasValue && older.HasValue) e.Hops[i].DelayBefore = newer.Value - older.Value;
        }

        // ---------------------------------------------------------------- Authentication-Results
        foreach (var f in headers.All("Authentication-Results"))
            e.AuthResults.Add(ParseAuthResults(f.Value, "Authentication-Results", f.Index));
        foreach (var f in headers.All("ARC-Authentication-Results"))
        {
            var tags = Regex.Match(f.Value, @"^\s*i\s*=\s*(\d+)\s*;");
            var rest = tags.Success ? f.Value[tags.Length..] : f.Value;
            e.AuthResults.Add(ParseAuthResults(rest, "ARC-Authentication-Results" + (tags.Success ? " i=" + tags.Groups[1].Value : ""), f.Index));
        }
        e.ReceivedSpf = headers.First("Received-SPF");
        e.ArcInstances = headers.All("ARC-Seal").Count();

        foreach (var f in headers.All("DKIM-Signature"))
        {
            var t = HeaderBlock.ParseTags(f.Value);
            e.DkimSignatures.Add(new DkimSignature
            {
                Domain = DomainUtil.Normalize(t.GetValueOrDefault("d")),
                Selector = (t.GetValueOrDefault("s") ?? "").Trim(),
                Algorithm = t.GetValueOrDefault("a") ?? "",
                Identity = t.GetValueOrDefault("i") ?? "",
                SignedHeaders = t.GetValueOrDefault("h") ?? "",
                Signed = UnixTime(t.GetValueOrDefault("t")),
                Expires = UnixTime(t.GetValueOrDefault("x")),
                Raw = f.Value,
            });
        }

        DeriveVerdict(e);
        DeriveSendingIp(e);
        DeriveSpam(e);
        return e;
    }

    // ------------------------------------------------------------------ Authentication-Results

    public static AuthResultsHeader ParseAuthResults(string value, string source, int index)
    {
        var segments = SplitTopLevel(value, ';');
        string? servId = null;

        int start = 0;
        if (segments.Count > 0)
        {
            var first = HeaderBlock.StripComments(segments[0]).Trim();
            // Microsoft omits the authserv-id and starts directly with "spf=...".
            if (!Regex.IsMatch(first, @"^[A-Za-z0-9\-_/]+\s*=") )
            {
                servId = first.Split(' ', StringSplitOptions.RemoveEmptyEntries).FirstOrDefault();
                start = 1;
            }
        }

        var auth = new AuthResultsHeader { Source = source, Raw = value, Index = index, AuthServId = servId };
        for (int i = start; i < segments.Count; i++)
        {
            var comments = new List<string>();
            var body = HeaderBlock.StripComments(segments[i], comments).Trim();
            if (body.Length == 0 || body.Equals("none", StringComparison.OrdinalIgnoreCase)) continue;

            var tokens = Regex.Matches(body, @"[^\s=]+\s*=\s*(""[^""]*""|[^\s]*)|[^\s]+").Select(m => m.Value).ToList();
            if (tokens.Count == 0) continue;

            var mr = tokens[0].Split('=', 2);
            if (mr.Length != 2) continue;
            var method = mr[0].Trim().Split('/')[0].ToLowerInvariant();
            var am = new AuthMethod
            {
                Method = method,
                Result = mr[1].Trim().ToLowerInvariant(),
                Comment = string.Join("; ", comments),
            };
            foreach (var tok in tokens.Skip(1))
            {
                var kv = tok.Split('=', 2);
                if (kv.Length != 2) continue;
                var k = kv[0].Trim();
                var v = kv[1].Trim().Trim('"');
                if (!am.Props.ContainsKey(k)) am.Props[k] = v;
            }
            auth.Methods.Add(am);
        }
        return auth;
    }

    /// <summary>Splits on a separator outside comments and quotes.</summary>
    private static List<string> SplitTopLevel(string value, char separator)
    {
        var parts = new List<string>();
        int depth = 0;
        bool quoted = false;
        int start = 0;
        for (int i = 0; i < value.Length; i++)
        {
            char c = value[i];
            if (c == '\\') { i++; continue; }
            if (depth == 0 && c == '"') quoted = !quoted;
            else if (!quoted && c == '(') depth++;
            else if (!quoted && c == ')' && depth > 0) depth--;
            else if (!quoted && depth == 0 && c == separator)
            {
                parts.Add(value[start..i]);
                start = i + 1;
            }
        }
        parts.Add(value[start..]);
        return parts.Where(p => p.Trim().Length > 0).ToList();
    }

    private static void DeriveVerdict(MailEvidence e)
    {
        // The topmost Authentication-Results is the one added by the last receiving system:
        // the only trustworthy one, because everything below it came from outside.
        var primary = e.AuthResults.Where(a => a.Source == "Authentication-Results").OrderBy(a => a.Index).FirstOrDefault()
                      ?? e.AuthResults.OrderBy(a => a.Index).FirstOrDefault();
        e.PrimaryAuth = primary;

        if (primary is not null)
        {
            var spf = primary.Get("spf");
            if (spf is not null)
            {
                e.SpfResult = spf.Result;
                var mailFrom = spf.Prop("smtp.mailfrom");
                if (!string.IsNullOrEmpty(mailFrom)) e.SpfDomain = DomainUtil.DomainOf(mailFrom);
            }

            foreach (var d in primary.All("dkim"))
            {
                // Microsoft: "dkim=none (message not signed) header.d=none" carries no domain.
                if (d.Result == "none") continue;
                var domain = d.Prop("header.d") ?? DomainUtil.DomainOf(d.Prop("header.i"));
                e.DkimResults.Add((d.Result, DomainUtil.Normalize(domain), d.Prop("header.s")));
            }

            var dmarc = primary.Get("dmarc");
            if (dmarc is not null)
            {
                e.DmarcResult = dmarc.Result;
                e.DmarcAction = dmarc.Prop("action");
                // Google: "dmarc=pass (p=REJECT sp=REJECT dis=NONE)"
                var p = Regex.Match(dmarc.Comment, @"\bp=([A-Za-z]+)");
                if (p.Success) e.DmarcPolicyThen = p.Groups[1].Value.ToLowerInvariant();
                var hf = dmarc.Prop("header.from");
                if (string.IsNullOrEmpty(e.FromDomain) && !string.IsNullOrEmpty(hf)) e.FromDomain = DomainUtil.Normalize(hf);
            }

            var comp = primary.Get("compauth");
            if (comp is not null)
            {
                e.CompAuth = comp.Result;
                e.CompAuthReason = comp.Prop("reason");
            }
        }

        // Received-SPF as a fallback (Exchange on-premises, some gateways).
        if (e.SpfResult is null && !string.IsNullOrEmpty(e.ReceivedSpf))
        {
            var word = e.ReceivedSpf.Trim().Split(' ', '(', ';')[0].ToLowerInvariant();
            if (word.Length > 0) e.SpfResult = word;
            var envFrom = Regex.Match(e.ReceivedSpf, @"envelope-from=""?<?([^\s;>""]+)", RegexOptions.IgnoreCase);
            if (envFrom.Success) e.SpfDomain = DomainUtil.DomainOf(envFrom.Groups[1].Value);
        }

        e.SpfDomain ??= e.EnvelopeDomain;
        e.EnvelopeDomain ??= e.SpfDomain;
    }

    private static void DeriveSendingIp(MailEvidence e)
    {
        // 1. Microsoft: spf=pass (sender IP is 203.0.113.5)
        foreach (var a in e.AuthResults.OrderBy(a => a.Index))
        {
            foreach (var m in a.Methods)
            {
                var c = Regex.Match(m.Comment, @"sender IP is ([0-9a-fA-F:.]+)");
                if (c.Success && NetUtil.TryParseIp(c.Groups[1].Value, out var ip))
                {
                    Set(e, ip, "Authentication-Results (sender IP is ...)");
                    goto host;
                }
                foreach (var key in new[] { "smtp.remote-ip", "policy.iprev", "smtp.client-ip", "client-ip" })
                {
                    if (NetUtil.TryParseIp(m.Prop(key), out var ip2))
                    {
                        Set(e, ip2, $"Authentication-Results ({key})");
                        goto host;
                    }
                }
                // Google: "domain of x designates 203.0.113.5 as permitted sender"
                var g = Regex.Match(m.Comment, @"designates ([0-9a-fA-F:.]+) as");
                if (g.Success && NetUtil.TryParseIp(g.Groups[1].Value, out var ip3))
                {
                    Set(e, ip3, "Authentication-Results (designates ... as permitted sender)");
                    goto host;
                }
                var gNot = Regex.Match(m.Comment, @"does not designate ([0-9a-fA-F:.]+) as");
                if (gNot.Success && NetUtil.TryParseIp(gNot.Groups[1].Value, out var ip4))
                {
                    Set(e, ip4, "Authentication-Results (does not designate ...)");
                    goto host;
                }
            }
        }

        // 2. Received-SPF client-ip=
        if (e.ReceivedSpf is not null)
        {
            var m = Regex.Match(e.ReceivedSpf, @"client-ip=([0-9a-fA-F:.]+)", RegexOptions.IgnoreCase);
            if (m.Success && NetUtil.TryParseIp(m.Groups[1].Value, out var ip))
            {
                Set(e, ip, "Received-SPF (client-ip)");
                goto host;
            }
        }

        // 3. Exchange Online Protection: X-Forefront-Antispam-Report: CIP:203.0.113.5;...
        var forefront = e.Headers.First("X-Forefront-Antispam-Report");
        if (forefront is not null)
        {
            var m = Regex.Match(forefront, @"CIP:([0-9a-fA-F:.]+)");
            if (m.Success && NetUtil.TryParseIp(m.Groups[1].Value, out var ip))
            {
                Set(e, ip, "X-Forefront-Antispam-Report (CIP)");
                goto host;
            }
        }

        // 4. The hop where the mail entered the receiving organisation: the oldest hop whose
        //    "by" host belongs to the same organisation as the server that wrote the trusted
        //    Authentication-Results. Internal hops above it may use any addresses at all.
        var servId = e.PrimaryAuth?.AuthServId;
        if (!string.IsNullOrEmpty(servId) && servId.Contains('.'))
        {
            var entry = e.Hops.AsEnumerable().Reverse()
                .FirstOrDefault(h => h.ByHost is not null && h.FromIp is not null && NetUtil.IsPublic(h.FromIp)
                                     && DomainUtil.AlignedRelaxed(h.ByHost, servId));
            if (entry is not null)
            {
                Set(e, entry.FromIp!, $"Received chain (hop {entry.Index + 1}: where the mail entered {DomainUtil.OrgDomain(servId)})");
                goto host;
            }
        }

        // 5. The topmost hop received from a public address.
        var hop = e.Hops.FirstOrDefault(h => h.FromIp is not null && NetUtil.IsPublic(h.FromIp));
        if (hop is not null)
        {
            Set(e, hop.FromIp!, $"Received chain (hop {hop.Index + 1}, first public address from the top)");
        }

        host:
        if (e.SendingIp is not null)
        {
            var match = e.Hops.FirstOrDefault(h => h.FromIp is not null && h.FromIp.Equals(e.SendingIp));
            if (match is not null)
            {
                e.SendingHost = match.FromHost;
                e.SendingHelo = match.FromHelo;
            }
        }
    }

    private static void Set(MailEvidence e, IPAddress ip, string source)
    {
        e.SendingIp = ip;
        e.SendingIpSource = source;
    }

    private static void DeriveSpam(MailEvidence e)
    {
        var h = e.Headers;
        var ff = h.First("X-Forefront-Antispam-Report");
        if (ff is not null)
        {
            var scl = Regex.Match(ff, @"SCL:(-?\d+)");
            if (scl.Success && int.TryParse(scl.Groups[1].Value, NumberStyles.Integer, CultureInfo.InvariantCulture, out var sclValue)) e.Scl = sclValue;
            var sfv = Regex.Match(ff, @"SFV:([A-Z]+)");
            if (sfv.Success) e.SpamVerdict = "SFV:" + sfv.Groups[1].Value;
        }
        if (e.Scl is null && int.TryParse(h.First("X-MS-Exchange-Organization-SCL")?.Trim(), NumberStyles.Integer, CultureInfo.InvariantCulture, out var scl2))
            e.Scl = scl2;

        var ms = h.First("X-Microsoft-Antispam");
        if (ms is not null)
        {
            var bcl = Regex.Match(ms, @"BCL:(\d+)");
            if (bcl.Success && int.TryParse(bcl.Groups[1].Value, NumberStyles.Integer, CultureInfo.InvariantCulture, out var bclValue)) e.Bcl = bclValue;
        }

        var status = h.First("X-Spam-Status");
        if (status is not null)
        {
            var score = Regex.Match(status, @"score=(-?[\d.]+)");
            var req = Regex.Match(status, @"required=(-?[\d.]+)");
            if (score.Success && double.TryParse(score.Groups[1].Value, NumberStyles.Float, CultureInfo.InvariantCulture, out var s)) e.SpamScore = s;
            if (req.Success && double.TryParse(req.Groups[1].Value, NumberStyles.Float, CultureInfo.InvariantCulture, out var r)) e.SpamThreshold = r;
            e.SpamVerdict ??= "X-Spam-Status: " + status.Split(',')[0].Trim();
        }
        if (e.SpamScore is null && double.TryParse(h.First("X-Spam-Score")?.Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out var s2))
            e.SpamScore = s2;
    }

    // ------------------------------------------------------------------ Received

    private static readonly Regex RxFrom = new(@"\bfrom\s+(\S+)(?:\s*\(([^)]*)\))?", RegexOptions.IgnoreCase | RegexOptions.Compiled);
    private static readonly Regex RxBy = new(@"\bby\s+(\S+)", RegexOptions.IgnoreCase | RegexOptions.Compiled);
    private static readonly Regex RxWith = new(@"\bwith\s+(\S+)", RegexOptions.IgnoreCase | RegexOptions.Compiled);
    private static readonly Regex RxIp = new(@"\[?(?:IPv6:)?((?:\d{1,3}\.){3}\d{1,3}|[0-9a-fA-F]{0,4}(?::[0-9a-fA-F]{0,4}){2,7})\]?", RegexOptions.Compiled);
    private static readonly Regex RxTls = new(@"(version=TLS[^\s,)]*(?:,?\s*cipher=[^\s,)]+)?|TLSv?1\.[0-3][^;)]*|using TLS[^;)]*)", RegexOptions.IgnoreCase | RegexOptions.Compiled);

    public static ReceivedHop ParseReceived(string value, int index)
    {
        // RFC 5321 4.4: the date-time follows the last ';'.
        DateTimeOffset? time = null;
        int semi = value.LastIndexOf(';');
        var main = value;
        if (semi >= 0)
        {
            time = ParseDate(value[(semi + 1)..]);
            main = value[..semi];
        }

        string? helo = null, host = null, by = null, with = null;
        IPAddress? ip = null;

        var fm = RxFrom.Match(main);
        if (fm.Success)
        {
            helo = fm.Groups[1].Value.Trim('[', ']');
            var paren = fm.Groups[2].Success ? fm.Groups[2].Value : "";
            // "(mail.example.com [203.0.113.5])", "([203.0.113.5])", "(203.0.113.5)"
            foreach (Match m in RxIp.Matches(paren))
            {
                if (NetUtil.TryParseIp(m.Groups[1].Value, out var candidate)) { ip = candidate; break; }
            }
            var hostMatch = Regex.Match(paren, @"^\s*([A-Za-z0-9][A-Za-z0-9.\-]*\.[A-Za-z]{2,})");
            if (hostMatch.Success) host = hostMatch.Groups[1].Value;
            // "from [203.0.113.5]" with nothing in parentheses
            if (ip is null && NetUtil.TryParseIp(helo, out var heloIp)) ip = heloIp;
        }
        var bm = RxBy.Match(main);
        if (bm.Success) by = bm.Groups[1].Value;
        var wm = RxWith.Match(main);
        if (wm.Success) with = wm.Groups[1].Value;
        var tm = RxTls.Match(main);

        return new ReceivedHop
        {
            Index = index,
            Raw = value,
            FromHelo = helo,
            FromHost = host,
            FromIp = ip,
            ByHost = by,
            With = with,
            Tls = tm.Success ? tm.Value.Trim() : (with is not null && with.Contains("ESMTPS", StringComparison.OrdinalIgnoreCase) ? "ESMTPS" : null),
            Time = time,
        };
    }

    // ------------------------------------------------------------------ dates

    public static DateTimeOffset? ParseDate(string? text)
    {
        if (string.IsNullOrWhiteSpace(text)) return null;
        var s = Regex.Replace(text, @"\([^)]*\)", " ");          // "(CEST)", "(UTC)"
        s = Regex.Replace(s, @"\s+", " ").Trim();
        s = Regex.Replace(s, @"^[A-Za-z]{3},\s*", "");            // weekday
        // "+0200" -> "+02:00" for the parser
        s = Regex.Replace(s, @"([+-])(\d{2})(\d{2})$", "$1$2:$3");
        s = Regex.Replace(s, @"\s(GMT|UT|UTC|Z)$", " +00:00");

        string[] formats =
        {
            "d MMM yyyy H:mm:ss zzz", "d MMM yyyy H:mm zzz", "d MMM yy H:mm:ss zzz",
            "d MMM yyyy H:mm:ss.fffffff zzz", "d MMM yyyy H:mm:ss",
        };
        if (DateTimeOffset.TryParseExact(s, formats, CultureInfo.InvariantCulture, DateTimeStyles.AllowWhiteSpaces, out var dto))
            return dto;
        if (DateTimeOffset.TryParse(s, CultureInfo.InvariantCulture, DateTimeStyles.AllowWhiteSpaces, out dto))
            return dto;
        return null;
    }

    private static DateTimeOffset? UnixTime(string? text)
    {
        if (long.TryParse(text?.Trim(), NumberStyles.Integer, CultureInfo.InvariantCulture, out var seconds) && seconds > 0 && seconds < 32503680000)
            return DateTimeOffset.FromUnixTimeSeconds(seconds);
        return null;
    }
